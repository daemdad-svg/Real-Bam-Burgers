// Helper function to get translation
export const getTranslation = (key, language = 'en') => {
  const keys = key.split('.');
  let value = translations;
  
  for (const k of keys) {
    value = value?.[k];
    if (!value) return key;
  }
  
  return value[language] || value.en || key;
};
